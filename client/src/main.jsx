/**
 * Application Entry Point
 * -----------------------
 * Renders the React root into the DOM, configuring BrowserRouter and global Providers.
 * 
 * Viva Concepts:
 * - ReactDOM.createRoot: React 18 Concurrent Root API.
 * - Provider Hierarchy: BrowserRouter -> AuthProvider -> CartProvider -> App.
 */

import React from 'react';
import ReactDOM from 'react-dom/client';
import { BrowserRouter } from 'react-router-dom';
import App from './App.jsx';
import { AuthProvider } from './context/AuthContext.jsx';
import { CartProvider } from './context/CartContext.jsx';
import { WishlistProvider } from './context/WishlistContext.jsx';
import './index.css';

ReactDOM.createRoot(document.getElementById('root')).render(
  <React.StrictMode>
    <BrowserRouter>
      <AuthProvider>
        <CartProvider>
          <WishlistProvider>
            <App />
          </WishlistProvider>
        </CartProvider>
      </AuthProvider>
    </BrowserRouter>
  </React.StrictMode>
);
